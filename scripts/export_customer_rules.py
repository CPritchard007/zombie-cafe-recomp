#!/usr/bin/env python3
"""Decode characterData.bin.mid using doInitDataInternal's native read order.
ELF 0x242d4c–0x24315c (Ghidra addresses add 0x10000).
Customer selector: Cafe::getDataForRandomCustomer, Ghidra 0x000c0164.
"""
import struct,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
b=(root/'recovered/apk/assets/data/characterData.bin.mid').read_bytes();p=0
def take(f):
 global p
 v=struct.unpack_from(f,b,p);p+=struct.calcsize(f);return v[0] if len(v)==1 else list(v)
def text():
 global p
 n=take('>H');v=b[p:p+n].decode('utf8');p+=n;return v
rows=[]
for i in range(take('>H')):
 r={'id':i,'level':take('>B'),'weight':take('>B'),'rating':take('>B'),'name':text(),'art':text(),'name2':text(),'sheet':take('>B')}
 r['stats']=take('>i7h');r['bool']=take('>?');r['int']=take('>i');r['bytes']=take('>2B');r['f']=take('<f');r['i2']=take('>i');r['floats']=take('<2f');r['byte']=take('>B');r['short']=take('>h');r['f2']=take('<f');r['description']=text();r['zdescription']=text();rows.append(r)
assert p==len(b),(p,len(b))
elf=(root/'recovered/apk/lib/armeabi/libZombieCafeAndroid.so').read_bytes()
# Native object offsets: minimum level, selection weight, and rating / 255.
assert struct.unpack_from('<I',elf,0xb025c)[0]==0xaec
assert struct.unpack_from('<I',elf,0xb0260)[0]==0xaf4
assert struct.unpack_from('<f',elf,0x243100)[0]==255
assert [struct.unpack_from('<i',elf,a-0x10000)[0] for a in [0x241190,0x241194,0x241198]]==[1100,1101,-1102]
forms=json.loads((root/'web/dist/assets/original/characters.json').read_text())['forms']
legacy=[next(f for f in forms if f['name']==name) for name in ['generic-human','oldman-human','businessman-human']]
legacy_ids={f['id'] for f in legacy}
humans=legacy+[f for f in forms if f['name'].endswith('-human') and f['id'] not in legacy_ids]
by_name={}
for i,f in enumerate(humans):by_name.setdefault(f['name'],i)
rules=[]
for r in rows:
 variant=by_name.get(r['art']+'-human')
 if r['level']<255 and r['weight']>0:assert variant is not None,r
 rules.append(dict(id=r['id'],name=r['name'] or r['art'],variant=variant,minLevel=r['level'],minRatingByte=r['rating'],weight=r['weight'],eventOnly=r['id'] in [1100,1101,1102]))
(root/'web/dist/customer-rules.js').write_text('// Generated by scripts/export_customer_rules.py from original characterData.bin.mid.\nexport const CUSTOMER_RULES='+json.dumps(rules,separators=(',',':'))+';\n')
(root/'reports/customer-records.json').write_text(json.dumps({'source':'characterData.bin.mid','bytes':p,'records':rows},indent=2)+'\n')
print('Decoded',len(rows),'records to exact EOF;',sum(r['weight']>0 and r['minLevel']<255 and not r['eventOnly'] for r in rules),'ordinary visitor records')
