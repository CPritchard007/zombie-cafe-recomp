#!/usr/bin/env python3
"""Stable visitor appearance IDs from the recovered character atlas catalog."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]
forms=json.loads((root/'web/dist/assets/original/characters.json').read_text())['forms']
legacy=[next(f for f in forms if f['name']==name) for name in ['generic-human','oldman-human','businessman-human']]
ids={f['id'] for f in legacy}
humans=legacy+[f for f in forms if f['name'].endswith('-human') and f['id'] not in ids]
output='// Generated by scripts/export_human_forms.py. First three IDs preserve existing saves.\n'
output+='export const HUMAN_FORMS=Object.freeze('+json.dumps([{'id':f['id'],'name':f['name']} for f in humans],separators=(',',':'))+');\n'
(root/'web/dist/human-forms.js').write_text(output)
print(len(humans),'human appearances')
